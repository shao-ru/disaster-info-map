// =====================================================================
// 課題 1  選んだ県・市の情報を返す                         難易度 ★☆☆☆☆
// =====================================================================
//
// 画面で県と市を選ぶと、この関数が呼ばれます。
// 選ばれた市の情報を regions.cities の中から探して返してください。
//
// 引数
//   prefName : 選ばれた都道府県名   例："千葉県"
//   cityName : 選ばれた市区町村名   例："流山市"
//   regions  : data/static/regions.json の中身。regions.cities は次のような要素の配列です。
//     {
//       code: "12220",            市区町村コード
//       prefCode: "12",           都道府県コード
//       pref: "千葉県",
//       name: "流山市",
//       fullName: "千葉県流山市",
//       center: [139.91645, 35.86851],   中心 [経度, 緯度]
//       bbox: [最小経度, 最小緯度, 最大経度, 最大緯度],
//       count: 83                 避難所の数
//     }
//
// 戻り値
//   見つかった市の要素（上の形のオブジェクト）。見つからないときは null。
//
// ヒント
//   配列の中から条件に合うものを 1 つ探すには Array.prototype.find が便利です。
//
// 確認方法
//   ブラウザーで test.html を開き、「課題 1」がすべて ✅ になれば完成です。
// =====================================================================

export function getRegion(prefName, cityName, regions) {
  // ---- 仮の実装：何を選んでも柏市を返す（ここを書き換える） ----
  return regions.cities.find((c) => c.fullName === "千葉県柏市");
}
